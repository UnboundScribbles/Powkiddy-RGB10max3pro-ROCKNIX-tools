#!/bin/bash
# Godot Scan - find every Godot game dropped into ports/godot/games/ and make an
# EmulationStation entry for each one.
#
# Run this from the Ports menu after adding or removing a game. It does not
# launch anything. It:
#   1. looks in  ports/godot/games/*  for a Godot pack
#   2. reads the engine version out of the pack header
#   3. picks the closest PortMaster Godot runtime that can run it
#   4. writes one launcher per game, named "Godot - <name>.sh"
#   5. deletes launchers for games that are no longer there
#   6. writes a report to ports/godot/godot-scan.txt
#
# WHY THIS CAN BE AUTOMATIC
#   Every Godot .pck begins with 'GDPC' followed by the pack format and the
#   engine version that built it. Pack format 1 means Godot 3, which runs on
#   PortMaster's FRT runtimes. Pack format 2 means Godot 4, which runs on the
#   godot_4.x runtimes through westonpack. Nothing has to be guessed, and the
#   version in the header matches what hand-written ports choose: a 4.3.0 pack
#   gets godot_4.3, a 3.5.2 pack gets frt_3.5.2.
#
# WHERE TO PUT A GAME
#   ports/godot/games/<any name you like>/
#   Drop in the Linux or Windows download, extracted. A separate .pck is ideal;
#   an executable with the pack embedded works too, and the pack is carved out
#   of it once.

XDG_DATA_HOME=${XDG_DATA_HOME:-$HOME/.local/share}

if [ -d "/opt/system/Tools/PortMaster/" ]; then
  controlfolder="/opt/system/Tools/PortMaster"
elif [ -d "/opt/tools/PortMaster/" ]; then
  controlfolder="/opt/tools/PortMaster"
elif [ -d "$XDG_DATA_HOME/PortMaster/" ]; then
  controlfolder="$XDG_DATA_HOME/PortMaster"
else
  controlfolder="/roms/ports/PortMaster"
fi

source $controlfolder/control.txt
[ -f "$controlfolder/device_info.txt" ] && source "$controlfolder/device_info.txt"
[ -f "${controlfolder}/mod_${CFW_NAME}.txt" ] && source "${controlfolder}/mod_${CFW_NAME}.txt"

PORTSDIR="/$directory/ports"
GAMEDIR="$PORTSDIR/godot"
MARKER="# generated by Godot Scan"
REPORT="$GAMEDIR/godot-scan.txt"
PCKINFO="$GAMEDIR/pckinfo.py"

mkdir -p "$GAMEDIR/games" "$GAMEDIR/logs"

: > "$REPORT"
exec > >(tee -a "$REPORT") 2>&1
echo "== Godot Scan $(date)"
echo "ports folder : $PORTSDIR"

PYBIN="$(command -v python3 2>/dev/null)"
if [ -z "$PYBIN" ] || [ ! -f "$PCKINFO" ]; then
  pm_message "Cannot read pack files.

Needs python3 ($([ -n "$PYBIN" ] && echo found || echo MISSING)) and
$PCKINFO ($([ -f "$PCKINFO" ] && echo found || echo MISSING))"
  sleep 10
  exit 1
fi

# ---------------------------------------------------------------- runtimes
# Known runtimes plus whatever is already in the libs folder, so a newer one
# only has to be installed, never configured here. PortMaster downloads a
# known-but-missing runtime on first launch.
FRT_KNOWN="2.1.6 3.1.2 3.2.3 3.3.4 3.4.5 3.5.2 3.5.3 3.6"
G4_KNOWN="4.2 4.2.2 4.3 4.4 4.4.1 4.5 4.6.3 4.7.1"
G4_MONO_KNOWN="4.2.2_mono 4.3_mono 4.4_mono 4.4.1_mono 4.5_mono 4.6.3_mono 4.7.1_mono"

list_runtimes() {
  local prefix="$1" known="$2" v
  {
    for v in $known; do echo "${prefix}_${v}"; done
    for f in "$controlfolder/libs/${prefix}_"*.squashfs; do
      [ -f "$f" ] && basename "$f" .squashfs
    done
  } | sort -u -V
}

FRT_LIST="$(list_runtimes frt "$FRT_KNOWN")"
G4_LIST="$(list_runtimes godot "$G4_KNOWN $G4_MONO_KNOWN")"
echo "frt runtimes   : $(echo $FRT_LIST | sed 's/frt_//g')"
echo "godot runtimes : $(echo $G4_LIST | sed 's/godot_//g')"

# 3.5.2 -> 30502 so versions compare as integers. Suffixes like _v1 or -dev on
# a runtime name are ignored for comparison.
vnum() {
  local v="$(echo "$1" | sed 's/[^0-9.].*$//')"
  local a b c
  IFS=. read -r a b c <<<"$v"
  printf '%d%02d%02d\n' "${a:-0}" "${b:-0}" "${c:-0}"
}

# Oldest runtime that is still new enough, which is the closest match. Falls
# back to the newest available when the game is newer than everything.
pick_runtime() {
  local list="$1" want="$2" mono="$3" r rv best="" newest=""
  local wn; wn=$(vnum "$want")
  for r in $list; do
    # A C# game needs a Mono build and nothing else will do, so each search
    # looks only at the half of the list that fits.
    case "$r" in
      *_mono) [ "$mono" = "1" ] || continue ;;
      *)      [ "$mono" = "1" ] && continue ;;
    esac
    rv="${r#*_}"
    newest="$r"
    if [ -z "$best" ] && [ "$(vnum "$rv")" -ge "$wn" ]; then best="$r"; fi
  done
  [ -z "$best" ] && best="$newest"
  echo "$best"
}

# ---------------------------------------------------------------- clear old
removed=0
for f in "$PORTSDIR"/Godot\ -\ *.sh; do
  [ -f "$f" ] || continue
  grep -qF "$MARKER" "$f" 2>/dev/null || continue
  rm -f "$f"
  removed=$((removed + 1))
done
[ "$removed" -gt 0 ] && echo "cleared $removed old launcher(s)"

# ---------------------------------------------------------------- scan
found=0; ready=0; failed=0
SUMMARY=""

for d in "$GAMEDIR/games"/*/; do
  [ -d "$d" ] || continue
  name="$(basename "${d%/}")"
  case "$name" in .*) continue ;; esac

  echo ""
  echo "[$name]"

  INFO="$("$PYBIN" "$PCKINFO" "${d%/}" --extract 2>&1)"
  PCK_OK=0; PCK_PATH=""; PCK_SOURCE=""; PACK_FORMAT=""; GODOT_VERSION=""
  GODOT_MAJOR=""; EMBEDDED=0; EXTRACTED=0; MONO=0; PCK_ERROR=""
  while IFS='=' read -r k v; do
    case "$k" in
      PCK_OK|PCK_PATH|PCK_SOURCE|PACK_FORMAT|GODOT_VERSION|GODOT_MAJOR|EMBEDDED|EXTRACTED|MONO|PCK_ERROR)
        eval "$k=\"\$v\"" ;;
    esac
  done <<<"$INFO"

  if [ "$PCK_OK" != "1" ]; then
    echo "  no Godot pack found${PCK_ERROR:+ ($PCK_ERROR)}"
    SUMMARY="$SUMMARY
$name: SKIPPED, no pack"
    failed=$((failed + 1))
    continue
  fi

  found=$((found + 1))
  echo "  pack         : $PCK_PATH"
  [ "$EMBEDDED" = "1" ] && echo "  embedded in  : $PCK_SOURCE$([ "$EXTRACTED" = "1" ] && echo " (carved out)")"
  echo "  engine       : Godot $GODOT_VERSION (pack format $PACK_FORMAT)"
  [ "$MONO" = "1" ] && echo "  C# / Mono    : yes"

  if [ "$PACK_FORMAT" = "1" ] || [ "$GODOT_MAJOR" -lt 4 ] 2>/dev/null; then
    PROFILE="frt"
    RUNTIME="$(pick_runtime "$FRT_LIST" "$GODOT_VERSION" 0)"
  else
    PROFILE="godot4"
    RUNTIME="$(pick_runtime "$G4_LIST" "$GODOT_VERSION" "$MONO")"
  fi

  if [ -z "$RUNTIME" ]; then
    echo "  no runtime available for this engine"
    SUMMARY="$SUMMARY
$name: no runtime for Godot $GODOT_VERSION"
    failed=$((failed + 1))
    continue
  fi

  # A per-game override: put a runtime name in games/<name>/runtime.txt
  if [ -f "${d}runtime.txt" ]; then
    ovr="$(tr -d ' \r\n' < "${d}runtime.txt")"
    [ -n "$ovr" ] && { RUNTIME="$ovr"; echo "  runtime.txt  : override"; }
  fi

  echo "  runtime      : $RUNTIME ($PROFILE)"
  if [ "$(vnum "${RUNTIME#*_}")" -eq "$(vnum "$GODOT_VERSION")" ]; then
    echo "  match        : exact"
  else
    echo "  match        : nearest, so this may need tuning"
  fi
  case "$RUNTIME" in
    *_mono) ;;
    *) [ "$MONO" = "1" ] && echo "  WARNING      : C# game on a runtime without Mono, it will probably not start" ;;
  esac

  ready=$((ready + 1))
  SUMMARY="$SUMMARY
$name: Godot $GODOT_VERSION -> $RUNTIME"

  out="$PORTSDIR/Godot - $name.sh"
  {
    echo "#!/bin/bash"
    echo "$MARKER on $(date)"
    echo "XDG_DATA_HOME=\${XDG_DATA_HOME:-\$HOME/.local/share}"
    echo 'if [ -d "/opt/system/Tools/PortMaster/" ]; then controlfolder="/opt/system/Tools/PortMaster"'
    echo 'elif [ -d "/opt/tools/PortMaster/" ]; then controlfolder="/opt/tools/PortMaster"'
    echo 'elif [ -d "$XDG_DATA_HOME/PortMaster/" ]; then controlfolder="$XDG_DATA_HOME/PortMaster"'
    echo 'else controlfolder="/roms/ports/PortMaster"; fi'
    echo 'source $controlfolder/control.txt'
    echo "exec \"/\$directory/ports/godot/run.sh\" \"$name\" \"$RUNTIME\" \"$PROFILE\" \"$PCK_PATH\""
  } > "$out"
  chmod 666 "$out" 2>/dev/null
  chmod +x "$out" 2>/dev/null
  echo "  launcher     : Godot - $name.sh"
done

echo ""
echo "============================================"
echo "  games: $found    ready: $ready    skipped: $failed"
echo "============================================"

if [ "$found" -eq 0 ]; then
  pm_message "No Godot games found.

Put each game in its own folder here:

ports/godot/games/<name>/

Extract the Linux or Windows download into it. A .pck is ideal; an executable
with the pack embedded works too. Then run Godot Scan again."
  sleep 8
  exit 0
fi

pm_message "Found $found game(s). $ready ready to play.
$SUMMARY

Each one is now its own entry in the Ports menu, named Godot - <game>.

Refresh your gamelist or restart EmulationStation to see them.
Full detail in ports/godot/godot-scan.txt"
sleep 5
exit 0

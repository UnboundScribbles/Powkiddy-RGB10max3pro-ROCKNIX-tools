#!/bin/bash
# RenPy Scan - find every Ren'Py game dropped into ports/renpy/games/ and make
# an EmulationStation entry for each one.
#
# Run this from the Ports menu after adding or removing a game. It does not
# launch anything. It:
#   1. looks in  ports/renpy/games/*  for a folder containing a Ren'Py "game" dir
#   2. reads each game's script_version.txt to work out which Ren'Py runtime it needs
#   3. writes one launcher per game into the ports folder, named "RenPy - <name>.sh"
#   4. deletes launchers for games that are no longer there
#   5. writes a report to ports/renpy/renpy-scan.txt
#
# WHY A RUNTIME HAS TO BE CHOSEN PER GAME
#   A game's scripts are compiled bytecode stamped with the Ren'Py version that
#   built them. A runtime can load its own version or older, never newer. So a
#   game built with 8.5.2 cannot run on the 8.3.4 runtime, and this reports that
#   up front instead of letting it fail at launch.
#
# WHERE TO PUT A GAME
#   ports/renpy/games/<any name you like>/game/...
#   Copy the "game" folder out of the PC download. The download's lib/ and renpy/
#   folders are not used and can be left behind.
#   A whole extracted download also works: if <name>/game is missing, one level
#   deeper is checked, so <name>/TheGame-1.0-pc/game is found too.

XDG_DATA_HOME=${XDG_DATA_HOME:-$HOME/.local/share}

if [ -d "/opt/system/Tools/PortMaster/" ]; then
  controlfolder="/opt/system/Tools/PortMaster"
elif [ -d "/opt/tools/PortMaster/" ]; then
  controlfolder="/opt/tools/PortMaster"
elif [ -d "$XDG_DATA_HOME/PortMaster/" ]; then
  controlfolder="$XDG_DATA_HOME/PortMaster"
else
  controlfolder="/roms/ports/PortMaster"
fi

source $controlfolder/control.txt
[ -f "${controlfolder}/mod_${CFW_NAME}.txt" ] && source "${controlfolder}/mod_${CFW_NAME}.txt"

PORTSDIR="/$directory/ports"
GAMEDIR="$PORTSDIR/renpy"
MARKER="# generated by RenPy Scan"
REPORT="$GAMEDIR/renpy-scan.txt"

mkdir -p "$GAMEDIR/games" "$GAMEDIR/logs" "$GAMEDIR/runtimes"

# The console is not visible on this device, so everything goes to the report.
: > "$REPORT"
exec > >(tee -a "$REPORT") 2>&1
echo "== RenPy Scan $(date)"
echo "ports folder : $PORTSDIR"
echo ""

# ---------------------------------------------------------------- version map
# Turns 8.3.4 into 80304 so versions can be compared as plain integers.
vnum() { printf '%d%02d%02d\n' "${1:-0}" "${2:-0}" "${3:-0}"; }

# Runtimes come from three places:
#   1. the two PortMaster ships for aarch64, which it downloads on demand
#   2. anything else already sitting in PortMaster's libs folder, so a newer
#      runtime only has to be installed, never configured here
#   3. ports/renpy/runtimes/renpy_<version>/ , an unpacked Ren'Py distribution
#      you assembled yourself. PortMaster's runtimes are repackaged official
#      Ren'Py builds, so a folder from the SDK works the same way and needs no
#      mksquashfs. See READ ME FIRST.txt.
RT_KNOWN="8.1.3 8.3.4"
RT_LIST="$(
  {
    for v in $RT_KNOWN; do echo "$v"; done
    for f in "$controlfolder/libs"/renpy_*.squashfs; do
      [ -f "$f" ] || continue
      b="$(basename "$f" .squashfs)"; echo "${b#renpy_}"
    done
    for d in "$GAMEDIR/runtimes"/renpy_*/; do
      [ -d "$d" ] || continue
      b="$(basename "${d%/}")"; echo "${b#renpy_}"
    done
  } | sort -u -V
)"
for d in "$GAMEDIR/runtimes"/renpy_*/; do
  [ -d "$d" ] && echo "local runtime  : $(basename "${d%/}")"
done
RT_NEWEST="$(echo "$RT_LIST" | tail -1)"
echo "runtimes known : $(echo $RT_LIST | tr '\n' ' ')"

# Reads script_version.txt and prints: <version text>|<runtime>|<note>
# The runtime chosen is the OLDEST one that is still new enough to read the
# game's compiled scripts, since a closer match has fewer removed APIs to trip
# an older game.
pick_runtime() {
  local gamedir="$1" raw maj min pat v rv note pick
  raw=""
  [ -f "$gamedir/script_version.txt" ] && raw="$(tr -d '\r' < "$gamedir/script_version.txt" | head -1)"

  if [ -z "$raw" ]; then
    echo "unknown|renpy_$RT_NEWEST|no script_version.txt, trying the newest runtime"
    return
  fi

  # Accepts "(8, 5, 2)" and "8.5.2" alike.
  read -r maj min pat <<<"$(echo "$raw" | tr -d '() ' | tr '.,' '  ')"
  min=${min:-0}; pat=${pat:-0}
  case "$maj$min$pat" in
    *[!0-9]*|"") echo "$raw|renpy_$RT_NEWEST|could not read the version, trying the newest runtime"; return ;;
  esac

  v=$(vnum "$maj" "$min" "$pat")
  note=""
  [ "$maj" -lt 8 ] && note="Ren'Py $maj game on an 8.x runtime, may or may not work"

  pick=""
  for rv in $RT_LIST; do
    read -r a b c <<<"$(echo "$rv" | tr '.' ' ')"
    if [ "$(vnum "$a" "$b" "$c")" -ge "$v" ]; then pick="$rv"; break; fi
  done

  if [ -z "$pick" ]; then
    echo "$raw|renpy_$RT_NEWEST|TOO NEW: needs Ren'Py $maj.$min.$pat, newest runtime here is $RT_NEWEST"
  else
    echo "$raw|renpy_$pick|$note"
  fi
}

# ---------------------------------------------------------------- find games
# A game folder is one that holds a Ren'Py "game" directory, either directly or
# one level down, which is what you get from extracting a download as-is.
resolve_game() {
  local d="$1" sub
  if [ -d "$d/game" ]; then echo "$d/game"; return 0; fi
  for sub in "$d"/*/; do
    [ -d "${sub}game" ] && { echo "${sub}game"; return 0; }
  done
  return 1
}

# ---------------------------------------------------------------- clear old
# Only files this script wrote are removed, so hand-made launchers are safe.
removed=0
for f in "$PORTSDIR"/RenPy\ -\ *.sh; do
  [ -f "$f" ] || continue
  grep -qF "$MARKER" "$f" 2>/dev/null || continue
  rm -f "$f"
  removed=$((removed + 1))
done
[ "$removed" -gt 0 ] && echo "cleared $removed old launcher(s)"

# ---------------------------------------------------------------- scan
found=0; ready=0; toonew=0
SUMMARY=""

for d in "$GAMEDIR/games"/*/; do
  [ -d "$d" ] || continue
  name="$(basename "$d")"
  case "$name" in .*) continue ;; esac

  gpath="$(resolve_game "${d%/}")" || {
    echo ""
    echo "[$name] no Ren'Py game folder inside, skipped"
    SUMMARY="$SUMMARY
$name: SKIPPED, no game folder"
    continue
  }

  found=$((found + 1))
  # Path relative to games/<name>, so the launcher stays valid if the card moves.
  rel="${gpath#"$GAMEDIR/games/$name/"}"

  IFS='|' read -r vtext runtime note <<<"$(pick_runtime "$gpath")"

  # A per-game override wins: put a runtime name in games/<name>/runtime.txt
  if [ -f "${d}runtime.txt" ]; then
    ovr="$(tr -d ' \r\n' < "${d}runtime.txt")"
    [ -n "$ovr" ] && { runtime="$ovr"; note="runtime.txt override"; }
  fi

  echo ""
  echo "[$name]"
  echo "  game folder    : $rel"
  echo "  script_version : $vtext"
  echo "  runtime        : $runtime"
  [ -n "$note" ] && echo "  note           : $note"

  if [ -n "$note" ] && [ "${note#TOO NEW}" != "$note" ]; then
    toonew=$((toonew + 1))
    SUMMARY="$SUMMARY
$name: NEEDS $vtext, too new"
  else
    ready=$((ready + 1))
    SUMMARY="$SUMMARY
$name: ready ($runtime)"
  fi

  # The launcher is a thin wrapper. All the real work lives in renpy/run.sh, so
  # fixing anything later means editing one file instead of every launcher.
  out="$PORTSDIR/RenPy - $name.sh"
  {
    echo "#!/bin/bash"
    echo "$MARKER on $(date)"
    echo "XDG_DATA_HOME=\${XDG_DATA_HOME:-\$HOME/.local/share}"
    echo 'if [ -d "/opt/system/Tools/PortMaster/" ]; then controlfolder="/opt/system/Tools/PortMaster"'
    echo 'elif [ -d "/opt/tools/PortMaster/" ]; then controlfolder="/opt/tools/PortMaster"'
    echo 'elif [ -d "$XDG_DATA_HOME/PortMaster/" ]; then controlfolder="$XDG_DATA_HOME/PortMaster"'
    echo 'else controlfolder="/roms/ports/PortMaster"; fi'
    echo 'source $controlfolder/control.txt'
    echo "exec \"/\$directory/ports/renpy/run.sh\" \"$name\" \"$runtime\" \"$rel\""
  } > "$out"
  chmod 666 "$out" 2>/dev/null
  chmod +x "$out" 2>/dev/null
  echo "  launcher       : RenPy - $name.sh"
done

echo ""
echo "============================================"
echo "  games found : $found    ready : $ready    too new : $toonew"
echo "============================================"

if [ "$found" -eq 0 ]; then
  pm_message "No Ren'Py games found.

Put each game in its own folder here:

ports/renpy/games/<name>/game/

Copy the 'game' folder out of the PC download. Then run RenPy Scan again."
  sleep 5
  exit 0
fi

MSG="Found $found game(s). $ready ready to play."
[ "$toonew" -gt 0 ] && MSG="$MSG
$toonew of them need a newer Ren'Py runtime than PortMaster has."
pm_message "$MSG
$SUMMARY

Each ready game is now its own entry in the Ports menu, named
RenPy - <game>.

Refresh your gamelist or restart EmulationStation to see them.
Full detail in ports/renpy/renpy-scan.txt"
sleep 5
exit 0
